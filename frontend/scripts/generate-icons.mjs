import sharp from 'sharp'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const source = await readFile(path.join(root, 'public/icon.svg'))
const iconsDir = path.join(root, 'public/icons')
await mkdir(iconsDir, { recursive: true })
for (const size of [192, 512])
  await sharp(source)
    .resize(size, size)
    .png()
    .toFile(path.join(iconsDir, `icon-${size}.png`))
await sharp(source)
  .resize(512, 512)
  .flatten({ background: '#2458d3' })
  .png()
  .toFile(path.join(iconsDir, 'maskable-512.png'))
// The mark stays inside Android adaptive icon and PWA maskable safe zones.
const res = path.join(root, 'android/app/src/main/res')
try {
  await readFile(path.join(res, 'values/strings.xml'))
} catch {
  console.log('PWA ikonas sagatavotas. Pēc cap add android vēlreiz izpildiet npm run assets.')
  process.exit(0)
}
for (const [density, size] of Object.entries({
  mdpi: 48,
  hdpi: 72,
  xhdpi: 96,
  xxhdpi: 144,
  xxxhdpi: 192,
})) {
  const dir = path.join(res, `mipmap-${density}`)
  await mkdir(dir, { recursive: true })
  for (const name of ['ic_launcher', 'ic_launcher_round'])
    await sharp(source)
      .resize(size, size)
      .png()
      .toFile(path.join(dir, `${name}.png`))
}
await mkdir(path.join(res, 'drawable'), { recursive: true })
const markPaths = [...source.toString().matchAll(/<path d="([^"]+)"/g)]
  .map(
    (match) =>
      `<path android:fillColor="@android:color/transparent" android:strokeColor="#FFFFFF" android:strokeWidth="19" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="${match[1]}"/>`,
  )
  .join('\n')
await writeFile(
  path.join(res, 'drawable/ic_launcher_foreground.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="512" android:viewportHeight="512">
  <group android:scaleX="0.72" android:scaleY="0.72" android:translateX="71.68" android:translateY="71.68">
    ${markPaths}
  </group>
</vector>
`,
)
await writeFile(
  path.join(res, 'drawable/splash_icon.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="512" android:viewportHeight="512">
  <path android:fillColor="#2458D3" android:pathData="M118,0H394Q512,0 512,118V394Q512,512 394,512H118Q0,512 0,394V118Q0,0 118,0Z"/>
  ${markPaths}
</vector>
`,
)
// Android selects this qualified resource on API 24+, so keep it identical.
await mkdir(path.join(res, 'drawable-v24'), { recursive: true })
await writeFile(
  path.join(res, 'drawable-v24/ic_launcher_foreground.xml'),
  await readFile(path.join(res, 'drawable/ic_launcher_foreground.xml')),
)
const adaptiveDir = path.join(res, 'mipmap-anydpi-v26')
await mkdir(adaptiveDir, { recursive: true })
for (const name of ['ic_launcher', 'ic_launcher_round']) {
  await writeFile(
    path.join(adaptiveDir, `${name}.xml`),
    `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@color/ic_launcher_background"/>
  <foreground android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
`,
  )
}
await writeFile(
  path.join(res, 'values/ic_launcher_background.xml'),
  '<?xml version="1.0" encoding="utf-8"?><resources><color name="ic_launcher_background">#2458D3</color></resources>\n',
)
// Legacy splash variants are generated by Capacitor; replace their content consistently.
const { readdir } = await import('node:fs/promises')
const splash = Buffer.from(
  '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024"><rect width="1024" height="1024" fill="#f5f7fb"/></svg>',
)
const logo = await sharp(source).resize(200, 200).png().toBuffer()
const splashImage = await sharp(splash)
  .composite([{ input: logo, gravity: 'center' }])
  .png()
  .toBuffer()
for (const entry of await readdir(res, { withFileTypes: true })) {
  if (!entry.isDirectory() || !entry.name.startsWith('drawable')) continue
  const target = path.join(res, entry.name, 'splash.png')
  try {
    await readFile(target)
    await writeFile(target, splashImage)
  } catch {
    /* No splash variant here. */
  }
}
console.log('PWA un Android prototipa ikonas un splash attēli sagatavoti.')
